    private Icons() {}

    public static void draw(GuiGraphics g, String[] icon, int x, int y, int scale, int color) {
        for (int r = 0; r < icon.length; r++) {
            String row = icon[r];
            int c = 0;
            while (c < row.length()) {
                if (row.charAt(c) != '#') {
                    c++;
                    continue;
                }
                int start = c;
                while (c < row.length() && row.charAt(c) == '#') c++;
                g.fill(x + start * scale, y + r * scale, x + c * scale, y + (r + 1) * scale, color);
            }
        }
    }
